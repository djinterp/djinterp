// SAME
//   ours is theirs, compared as the 64 unsigned bits both are.
#define SAME(_ours, _theirs)                                                   \
    _Static_assert((uint64_t)(_ours) == (uint64_t)(_theirs),                   \
                   #_ours " is " #_theirs)


