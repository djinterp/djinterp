/*
d_tests_write
  Writes bytes to a file.
*/
static bool
d_tests_write(
    const char*          _path,
    const unsigned char* _bytes,
    size_t               _length
)
{
    FILE* const out = fopen(_path, "wb");
    bool        ok  = (out != NULL);

    ok = ok && (fwrite(_bytes, 1u, _length, out) == _length);

    // a stream that fails to close has not written what it held
    if ( (out) &&
         (fclose(out) != 0) )
    {
        ok = false;
    }

    return ok;
}


/*
d_tests_entry_is
  Whether an entry reads as the bytes expected.
*/
static bool
d_tests_entry_is(
    struct d_zip*        _zip,
    const char*          _name,
    const unsigned char* _bytes,
    size_t               _length
)
{
    unsigned char* got    = NULL;
    size_t         length = 0;
    const bool     read   = d_zip_read(_zip, d_zip_find(_zip, _name), &got,
                                       &length, NULL, 0);
    const bool     same   = (read) &&
                            (length == _length) &&
                            ( (_length == 0) ||
                              (memcmp(got, _bytes, _length) == 0) );

    free(got);

    return same;
}


/*
d_tests_reading
  Tests the following:
  - the CRC-32 of the check string is the standard's
  - every entry of another implementation's archive reads, in its order
  - a stored entry, and fixed, dynamic and stored DEFLATE blocks, inflate
  - a damaged stream is refused, not misread
  - a file that is no archive is refused with a reason
*/
static void
d_tests_reading(
    const char* _work
)
{
    char           path[512];
    char           why[256];
    unsigned char  level0[512];
    char           dynamic[1024];
    size_t         used = 0;

    printf("reading\n");

    d_tests_check(d_zip_crc32(0ul, (const unsigned char*)"123456789", 9u)
                  == 0xCBF43926ul, "the CRC-32 check value");

    for (size_t at = 0; at < sizeof(level0); ++at)
    {
        level0[at] = (unsigned char)(at & 0xFFu);
    }

    for (int at = 0; at < 40; ++at)
    {
        used += (size_t)snprintf(&dynamic[used], sizeof(dynamic) - used,
                                 "<media id=\"%d\"/>\n", at);
    }

    (void)snprintf(path, sizeof(path), "%s/python.zip", _work);
    d_tests_check(d_tests_write(path, ARCHIVE, sizeof(ARCHIVE)),
                  "the archive is written");

    struct d_zip* const zip = d_zip_open(path, why, sizeof(why));

    d_tests_check(zip != NULL, "it opens");
    d_tests_check(d_zip_count(zip) == 5u, "five entries");
    d_tests_check((d_zip_count(zip) > 2u) &&
                  (strcmp(d_zip_name(zip, 2), "dynamic.xml") == 0),
                  "in the order written");
    d_tests_check(d_tests_entry_is(zip, "stored.txt",
                                   (const unsigned char*)"stored as it is\n",
                                   16u), "a stored entry");
    d_tests_check(d_tests_entry_is(zip, "fixed.xml",
                                   (const unsigned char*)
                                   "<sld name=\"Fixed\"/>\n", 20u),
                  "fixed Huffman codes");
    d_tests_check(d_tests_entry_is(zip, "dynamic.xml",
                                   (const unsigned char*)dynamic, used),
                  "dynamic Huffman codes");
    d_tests_check(d_tests_entry_is(zip, "level0.bin", level0,
                                   sizeof(level0)), "stored DEFLATE blocks");
    d_tests_check(d_tests_entry_is(zip, "empty", NULL, 0), "an empty entry");
    d_tests_check(d_zip_find(zip, "absent") == D_ZIP_NONE,
                  "an absent name is found nowhere");
    d_zip_free(zip);

    unsigned char damaged[sizeof(ARCHIVE)];

    memcpy(damaged, ARCHIVE, sizeof(ARCHIVE));

    // a byte in the middle of the dynamic stream's data is changed
    for (size_t at = 0; at + 11u < sizeof(damaged); ++at)
    {
        if (memcmp(&damaged[at], "dynamic.xml", 11u) == 0)
        {
            damaged[at + 11u + 40u] ^= 0x5Au;
            break;
        }
    }

    (void)snprintf(path, sizeof(path), "%s/damaged.zip", _work);

    struct d_zip* const bad = (d_tests_write(path, damaged, sizeof(damaged)))
                            ? d_zip_open(path, why, sizeof(why))
                            : NULL;
    unsigned char*      got    = NULL;
    size_t              length = 0;

    d_tests_check((bad) &&
                  (!d_zip_read(bad, d_zip_find(bad, "dynamic.xml"), &got,
                               &length, why, sizeof(why))) &&
                  (strstr(why, "damaged") != NULL),
                  "a damaged stream is refused");
    d_tests_check((bad) && d_tests_entry_is(bad, "fixed.xml",
                                            (const unsigned char*)
                                            "<sld name=\"Fixed\"/>\n", 20u),
                  "...and the entries around it still read");
    d_zip_free(bad);

    (void)snprintf(path, sizeof(path), "%s/not.zip", _work);
    d_tests_check(d_tests_write(path, (const unsigned char*)"not a zip", 9u) &&
                  (!d_zip_open(path, why, sizeof(why))) &&
                  (strstr(why, "not a ZIP archive") != NULL),
                  "a file that is no archive is refused");

    return;
}


/*
d_tests_saving
  Tests the following:
  - a replaced entry, and an added one, read back as given
  - every other entry reads back as it was
  - the archive's own file is not saved over
  - a new archive refuses a duplicate or empty name
*/
static void
d_tests_saving(
    const char* _work
)
{
    char path[512];
    char saved[512];
    char why[256];

    printf("saving\n");

    (void)snprintf(path, sizeof(path), "%s/python.zip", _work);
    (void)snprintf(saved, sizeof(saved), "%s/saved.zip", _work);

    struct d_zip* const zip = d_zip_open(path, why, sizeof(why));

    d_tests_check((zip) &&
                  (d_zip_replace(zip, d_zip_find(zip, "fixed.xml"),
                                 (const unsigned char*)"new", 3u)),
                  "an entry is replaced");
    d_tests_check((zip) &&
                  (d_zip_add(zip, "added.txt",
                             (const unsigned char*)"added", 5u)),
                  "an entry is added");
    d_tests_check((zip) &&
                  (!d_zip_add(zip, "added.txt",
                              (const unsigned char*)"x", 1u)),
                  "a name taken is refused");
    d_tests_check((zip) && (!d_zip_save(zip, path, why, sizeof(why))),
                  "the archive is not saved over itself");
    d_tests_check((zip) && (d_zip_save(zip, saved, why, sizeof(why))),
                  "the archive is saved elsewhere");
    d_zip_free(zip);

    struct d_zip* const back = d_zip_open(saved, why, sizeof(why));
    struct d_zip* const was  = d_zip_open(path, why, sizeof(why));

    d_tests_check((back) && (d_zip_count(back) == 6u), "six entries");
    d_tests_check(d_tests_entry_is(back, "fixed.xml",
                                   (const unsigned char*)"new", 3u),
                  "the replaced entry holds the new bytes");
    d_tests_check(d_tests_entry_is(back, "added.txt",
                                   (const unsigned char*)"added", 5u),
                  "the added entry holds its bytes");

    bool same = (back) && (was);

    // every entry not replaced reads as it did
    for (size_t at = 0; (same) && (at < d_zip_count(was)); ++at)
    {
        const char* const name = d_zip_name(was, at);
        unsigned char*    bytes = NULL;
        size_t            length = 0;

        if (strcmp(name, "fixed.xml") != 0)
        {
            same = d_zip_read(was, at, &bytes, &length, NULL, 0) &&
                   d_tests_entry_is(back, name, bytes, length);
            free(bytes);
        }
    }

    d_tests_check(same, "every other entry is as it was");
    d_zip_free(back);
    d_zip_free(was);

    struct d_zip* const made = d_zip_new();

    d_tests_check((made) &&
                  (!d_zip_add(made, "", (const unsigned char*)"x", 1u)),
                  "an empty name is refused");
    d_tests_check((made) && (d_zip_add(made, "a/b.txt", NULL, 0)),
                  "an empty entry is added");
    (void)snprintf(saved, sizeof(saved), "%s/made.zip", _work);
    d_tests_check((made) && (d_zip_save(made, saved, why, sizeof(why))),
                  "a new archive is saved");
    d_zip_free(made);

    struct d_zip* const reread = d_zip_open(saved, why, sizeof(why));

    d_tests_check(d_tests_entry_is(reread, "a/b.txt", NULL, 0),
                  "...and reads back");
    d_zip_free(reread);

    return;
}


/*
main
  Runs the checks, writing into the directory given or the current one.
*/
int
main(
    int    argc,
    char** argv
)
{
    const char* const work = (argc > 1) ? argv[1] : ".";

    d_tests_reading(work);
    d_tests_saving(work);

    printf("\n%d checks, %d failed\n", g_checks, g_failed);

    return (g_failed == 0) ? 0 : 1;
}
