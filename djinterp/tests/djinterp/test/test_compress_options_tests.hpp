// co_mutated
//   function: a pristine option set with row _i of the table applied.
inline dj::compress_options
co_mutated(
    std::size_t _i
)
{
    const std::vector<co_field> t = co_all_mutators();
    dj::compress_options        o;

    if (_i < t.size())
    {
        t[_i].apply(o);
    }

    return o;
}

// co_block_equal
//   function: dispatches to the module's comparator for the named block, so a
// table-driven test can ask "does THIS block's comparator see the change?"
// without a switch at every call site.
inline bool
co_block_equal(
    const char*                 _block,
    const dj::compress_options& _a,
    const dj::compress_options& _b
)
{
    const std::string b(_block);

    if (b == "deflate")
    {
        return dt::deflate_options_equal(_a.deflate, _b.deflate);
    }
    if (b == "bzip2") { return dt::bzip2_options_equal(_a.bzip2, _b.bzip2); }
    if (b == "lzma")  { return dt::lzma_options_equal(_a.lzma, _b.lzma); }
    if (b == "zstd")  { return dt::zstd_options_equal(_a.zstd, _b.zstd); }
    if (b == "lz4")   { return dt::lz4_options_equal(_a.lz4, _b.lz4); }
    if (b == "brotli")
    {
        return dt::brotli_options_equal(_a.brotli, _b.brotli);
    }

    // "" is the generic level, which no per-block comparator owns
    return true;
}

// co_contains
//   function: true iff _hay contains _needle as a substring.
inline bool
co_contains(
    const std::string& _hay,
    const std::string& _needle
)
{
    return (_hay.find(_needle) != std::string::npos);
}

// co_split_csv
//   function: splits a ", "-separated diff string into its field names, so a
// test can assert on exact membership and order rather than substrings (which
// would let "zstd.level" match inside "zstd.level_extra").
inline std::vector<std::string>
co_split_csv(
    const std::string& _s
)
{
    std::vector<std::string> out;
    std::size_t              start = 0;

    if (_s.empty())
    {
        return out;
    }

    for (;;)
    {
        const std::size_t at = _s.find(", ", start);

        if (at == std::string::npos)
        {
            out.push_back(_s.substr(start));
            break;
        }

        out.push_back(_s.substr(start, at - start));
        start = (at + 2u);
    }

    return out;
}

