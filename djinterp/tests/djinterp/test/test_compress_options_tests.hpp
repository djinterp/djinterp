// co_bump
//   function: the next value of a numeric or enumerated field.  Adding one to
// the CURRENT value keeps every mutator independent of the field's default, so
// a row never has to name a magic constant that a later default change would
// silently invalidate.
template<typename _T>
inline _T
co_bump(
    _T _v
)
{
    return static_cast<_T>(static_cast<int>(_v) + 1);
}

// co_bump_size
//   function: the size_t counterpart of co_bump, kept separate so the cast
// never narrows a 64-bit width through int.
inline std::size_t
co_bump_size(
    std::size_t _v
)
{
    return (_v + 1u);
}


// co_mutator_fn
//   type: moves exactly one field of an option set.
typedef void (*co_mutator_fn)(dj::compress_options&);

// co_field
//   struct: one row of the field table - the diff label the module must emit
// for this field, the codec block it belongs to, and the mutator that moves
// it.  `block` lets a per-block test filter the table without a second copy.
struct co_field
{
    const char*   label;
    const char*   block;
    co_mutator_fn apply;

    co_field(
        const char*   _label,
        const char*   _block,
        co_mutator_fn _apply
    )
        : label(_label),
          block(_block),
          apply(_apply)
    {}
};


