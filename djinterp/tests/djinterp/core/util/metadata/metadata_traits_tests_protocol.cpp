/*
tests_metadata_hostile_types
  The traits stay well-formed on types that are not classes at all.
  Tests the following:
  - none of the three unifiers holds for any member of the adversarial
    type zoo - void, function types, arrays, references, member pointers
    and the rest - so a detection idiom that assumed a class type would
    surface here rather than at some caller's site
  - the quantifier instantiates every cell rather than short-circuiting,
    so a trait that was ill-formed for one hostile type cannot hide behind
    an earlier false
  - each trait is a genuine bool trait, so the results above are real
    answers rather than accidental conversions
*/
bool
tests_metadata_hostile_types()
{
    // no hostile type carries the protocol
    D_MT_CHECK((test::holds_for_none<has_metadata,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));
    D_MT_CHECK((test::holds_for_none<has_metadata_type,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));
    D_MT_CHECK((test::holds_for_none<has_metadata_container_type,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));

    // the component traits are equally unbothered
    D_MT_CHECK((test::holds_for_none<has_metadata_data_member,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));
    D_MT_CHECK((test::holds_for_none<has_metadata_method,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));
    D_MT_CHECK((test::holds_for_none<has_metadata_nested_type,
                                     D_TEST_HOSTILE_TYPES_COMPLETE
                                     >::value));

    // and they really are bool traits
    D_MT_CHECK((test::is_bool_trait<has_metadata<md_member>>::value));
    D_MT_CHECK((test::is_bool_trait<has_metadata<int>>::value));
    D_MT_CHECK(
     (test::is_bool_trait<has_metadata_type<mdt_nested>>::value));

    return true;
}

/*
tests_metadata_value_companions
  The `_v` variable templates agree with their class traits.
  Tests the following:
  - all twelve companions report exactly what `::value` reports, on both
    a positive and a negative fixture.  Nine are generated by the
    detection macro and three are hand-written beside the unifying traits,
    so the two mechanisms are checked side by side
  - a companion that had drifted onto a neighbouring trait would disagree
    on a fixture where the two differ, which is why each is checked
    against a fixture that satisfies it and one that does not
*/
bool
tests_metadata_value_companions()
{
    // macro-generated companions, `metadata` family
    D_MT_CHECK(has_metadata_data_member_v<md_member> ==
               has_metadata_data_member<md_member>::value);
    D_MT_CHECK(has_metadata_data_member_v<md_none> ==
               has_metadata_data_member<md_none>::value);
    D_MT_CHECK(has_metadata_method_v<md_method> ==
               has_metadata_method<md_method>::value);
    D_MT_CHECK(has_metadata_method_v<md_none> ==
               has_metadata_method<md_none>::value);
    D_MT_CHECK(has_metadata_nested_type_v<md_nested> ==
               has_metadata_nested_type<md_nested>::value);
    D_MT_CHECK(has_metadata_nested_type_v<md_none> ==
               has_metadata_nested_type<md_none>::value);

    // hand-written companion for the unifier
    D_MT_CHECK(has_metadata_v<md_member> ==
               has_metadata<md_member>::value);
    D_MT_CHECK(has_metadata_v<md_none> ==
               has_metadata<md_none>::value);

    // `metadata_type` family
    D_MT_CHECK(has_metadata_type_data_member_v<mdt_member> ==
               has_metadata_type_data_member<mdt_member>::value);
    D_MT_CHECK(has_metadata_type_method_v<mdt_method> ==
               has_metadata_type_method<mdt_method>::value);
    D_MT_CHECK(has_metadata_type_nested_type_v<mdt_nested> ==
               has_metadata_type_nested_type<mdt_nested>::value);
    D_MT_CHECK(has_metadata_type_v<mdt_nested> ==
               has_metadata_type<mdt_nested>::value);
    D_MT_CHECK(has_metadata_type_v<md_none> ==
               has_metadata_type<md_none>::value);

    // `metadata_container_type` family
    D_MT_CHECK(has_metadata_container_type_data_member_v<mdc_member> ==
               has_metadata_container_type_data_member<
                   mdc_member>::value);
    D_MT_CHECK(has_metadata_container_type_method_v<mdc_method> ==
               has_metadata_container_type_method<mdc_method>::value);
    D_MT_CHECK(has_metadata_container_type_nested_type_v<mdc_nested> ==
               has_metadata_container_type_nested_type<
                   mdc_nested>::value);
    D_MT_CHECK(has_metadata_container_type_v<mdc_nested> ==
               has_metadata_container_type<mdc_nested>::value);
    D_MT_CHECK(has_metadata_container_type_v<md_none> ==
               has_metadata_container_type<md_none>::value);

    return true;
}

/*
tests_metadata_qualifier_transparency
  Querying a qualified type answers about the type underneath.
  Tests the following:
  - const, volatile and reference qualifications do not change the answer,
    for any of the three shapes.  The expression probes get this from
    binding through `const _Type&`, and the nested-alias probe gets it
    from cleaning the type before naming into it - two different
    mechanisms reaching the same result, which is worth pinning because
    only one of them would break if either changed
  - extraction is transparent in the same way, yielding the same cleaned
    type whether asked about T, const T, or T&
  - the transparency does not manufacture answers: a qualified form of a
    type that lacks the protocol still lacks it
*/
bool
tests_metadata_qualifier_transparency()
{
    // the expression shapes, through qualified forms
    D_MT_CHECK(has_metadata<const md_member>::value);
    D_MT_CHECK(has_metadata<md_member&>::value);
    D_MT_CHECK(has_metadata<const md_member&>::value);
    D_MT_CHECK(has_metadata<volatile md_member>::value);
    D_MT_CHECK(has_metadata<md_method&>::value);
    D_MT_CHECK(has_metadata<const md_method&>::value);

    // the nested-alias shape, which reaches the same answer by cleaning
    // the type rather than by binding a const reference
    D_MT_CHECK(has_metadata<const md_nested>::value);
    D_MT_CHECK(has_metadata<md_nested&>::value);
    D_MT_CHECK(has_metadata<const md_nested&>::value);

    // the other two families behave the same way
    D_MT_CHECK(has_metadata_type<const mdt_nested&>::value);
    D_MT_CHECK(has_metadata_container_type<const mdc_nested&>::value);
    D_MT_CHECK(has_metadata_type<mdt_member&>::value);

    // extraction is transparent too, and yields the cleaned type
    D_MT_CHECK(
     std::is_same_v<metadata_t<const md_member&>, md_payload>);
    D_MT_CHECK(std::is_same_v<metadata_t<md_nested&>, md_payload>);
    D_MT_CHECK(
     std::is_same_v<metadata_t<md_member>, metadata_t<md_member&>>);

    // ... and none of this invents a protocol that was never there
    D_MT_CHECK(!has_metadata<const md_none&>::value);
    D_MT_CHECK(!has_metadata<md_none&>::value);
    D_MT_CHECK(!mt_extracts_metadata<const md_none&>::value);

    return true;
}


