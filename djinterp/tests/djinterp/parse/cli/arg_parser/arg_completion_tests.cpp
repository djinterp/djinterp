// PROGRAM_NAMES
//   constant: the names the program defines, which a script for it holds.
const char* const PROGRAM_NAMES[] =
{
    "--help", "--number", "--verbose", "sub", "--inner"
};

// PROGRAM_NAME_COUNT
//   constant: how many names PROGRAM_NAMES holds.
const std::size_t PROGRAM_NAME_COUNT =
    sizeof(PROGRAM_NAMES) / sizeof(PROGRAM_NAMES[0]);

/**
 * @brief Defines the program the scripts complete: an option, a flag, and
 *        a subcommand with an option of its own.
 *
 * @param[in,out] _run  the run.
 * @return the subcommand.
 */
cli::command
define_program(
    run& _run
)
{
    (void)_run.app().add_option("-n,--number",
                                "a number");
    (void)_run.app().add_flag("--verbose",
                              "say more");

    cli::command sub = _run.app().add_subcommand("sub",
                                                 "a subcommand");

    (void)sub->add_option("--inner",
                          "an option of the subcommand");

    return sub;
}

/**
 * @brief A command's script for a shell, as the C library writes it.
 *
 * @param[in] _command  the command.
 * @param[in] _shell    the shell.
 * @param[in] _program  the name the shell runs the program by; empty for
 *                      the command's.
 * @return the script; empty when it could not be written.
 */
std::string
script_from_c(
    const cli::command& _command,
    cli::shell::value   _shell,
    const char*         _program
)
{
    std::string written;
    const int   result = d_arg_completion_script(_command.get(),
                                                 static_cast<int>(_shell),
                                                 cli::text(_program),
                                                 cli::string_sink(written));

    return (result == D_ARG_OK) ? written : std::string();
}

/**
 * @brief Writes what a command's script for a shell is: the status of the
 *        face's script written to a sink; whether that script, the face's
 *        made a std::string and the C library's are the same; and the
 *        script's length in lines, its first line, and which of the
 *        program's names it holds.
 *
 * @param[in,out] _run      the run.
 * @param[in]     _label    what the line names the script by.
 * @param[in]     _command  the command.
 * @param[in]     _shell    the shell.
 * @param[in]     _program  the name the shell runs the program by; empty
 *                          for the command's.
 */
void
write_script(
    run&                _run,
    const char*         _label,
    const cli::command& _command,
    cli::shell::value   _shell,
    const char*         _program
)
{
    const std::string      as_string = cli::completion_script(
                                           _command,
                                           _shell,
                                           cli::text(_program));
    std::string            sunk;
    const cli::status      into_sink = cli::completion_script(
                                           _command,
                                           _shell,
                                           cli::string_sink(sunk),
                                           cli::text(_program));
    const std::string      from_c    = script_from_c(_command,
                                                     _shell,
                                                     _program);
    std::size_t            lines     = 0u;
    std::string            held;
    std::string::size_type ended     = as_string.find('\n');

    // the lines, each ended by a line feed
    for (std::size_t index = 0u; index < as_string.size(); ++index)
    {
        lines += (as_string[index] == '\n') ? 1u : 0u;
    }

    // the program's names the script holds
    for (std::size_t index = 0u; index < PROGRAM_NAME_COUNT; ++index)
    {
        if (as_string.find(PROGRAM_NAMES[index]) != std::string::npos)
        {
            held += (held.empty() ? "" : ",");
            held += PROGRAM_NAMES[index];
        }
    }

    _run.note(std::string(_label) + " " + cli::shell_name(_shell) +
              ": sink=" + into_sink.get_name() + " same=" +
              ( ( (as_string == sunk) &&
                  (sunk == from_c) ) ? "1" : "0") +
              " lines=" + number(static_cast<unsigned long>(lines)) +
              " first=[" +
              escape(as_string.substr(0u,
                                      ended)) +
              "] names=[" + held + "]");

    return;
}

/**
 * @brief SCRIPTS 1: the program's script for each shell, for the name it
 *        has and for one given; a subcommand's; and the parser's, which
 *        converts to its root.
 *
 * @param[in,out] _run  the step's run.
 */
void
scripts_written(
    run& _run
)
{
    const cli::command sub = define_program(_run);

    for (std::size_t index = 0u; index < SHELL_COUNT; ++index)
    {
        write_script(_run,
                     "root",
                     _run.root(),
                     SHELL_LIST[index],
                     "");
    }

    for (std::size_t index = 0u; index < SHELL_COUNT; ++index)
    {
        write_script(_run,
                     "named",
                     _run.root(),
                     SHELL_LIST[index],
                     "my-prog");
    }

    write_script(_run,
                 "sub",
                 sub,
                 cli::shell::bash,
                 "");
    _run.note(std::string("parser: same=") +
              ( (cli::completion_script(_run.app(),
                                        cli::shell::zsh) ==
                 cli::completion_script(_run.root(),
                                        cli::shell::zsh)) ? "1" : "0"));

    return;
}

