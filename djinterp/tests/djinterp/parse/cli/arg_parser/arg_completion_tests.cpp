// 1.3    Failures
//------------------------------------------------------------------------------

/**
 * @brief A sink's write that takes nothing.
 *
 * @param[in] _context  unused.
 * @param[in] _data     unused.
 * @param[in] _size     unused.
 * @return 0: nothing taken.
 */
std::size_t
refuse_text(
    void*       _context,
    const void* _data,
    std::size_t _size
)
{
    (void)_context;
    (void)_data;
    (void)_size;

    return 0u;
}

/**
 * @brief FAILED 1: a script to a sink that takes nothing; for a command
 *        with no name to complete, to a sink and as a string, then with a
 *        name given.
 *
 * @param[in,out] _run  the step's run.
 */
void
failed_scripts(
    run& _run
)
{
    const ::d_pack_sink refusing = { &refuse_text, D_NULLPTR };
    std::string         sunk;
    cli::status         written;

    (void)define_program(_run);
    written = cli::completion_script(_run.root(),
                                     cli::shell::bash,
                                     refusing);
    _run.note(std::string("refused: ") + written.get_name());
    _run.app().name("");
    written = cli::completion_script(_run.root(),
                                     cli::shell::fish,
                                     cli::string_sink(sunk));
    _run.note(std::string("unnamed: ") + written.get_name() + " sink=[" +
              escape(sunk) + "] string=[" +
              escape(cli::completion_script(_run.root(),
                                            cli::shell::fish)) + "]");
    write_script(_run,
                 "given",
                 _run.root(),
                 cli::shell::fish,
                 "given");

    return;
}

