/**
 * @brief SHELLS 1: names read as shells, in any case, and names no shell
 *        has, which leave the shell given as it was; each shell's name.
 *
 * @param[in,out] _run  the step's run.
 */
void
shells_named(
    run& _run
)
{
    static const char* const NAMES[] =
    {
        "bash", "BASH", "Zsh", "fish", "powershell", "PowerShell", "pwsh",
        "PWSH", "sh", "", "bash ", "zshell"
    };

    for (std::size_t index = 0u;
         index < (sizeof(NAMES) / sizeof(NAMES[0]));
         ++index)
    {
        cli::shell::value found = cli::shell::zsh;
        const bool        known = cli::shell_from_name(NAMES[index],
                                                       found);

        _run.note("[" + escape(NAMES[index]) + "] -> known=" +
                  (known ? "1" : "0") + " shell=" +
                  cli::shell_name(found) + " " +
                  number(static_cast<long>(found)));
    }

    for (std::size_t index = 0u; index < SHELL_COUNT; ++index)
    {
        _run.note("name " +
                  number(static_cast<long>(SHELL_LIST[index])) + ": " +
                  cli::shell_name(SHELL_LIST[index]));
    }

    return;
}

