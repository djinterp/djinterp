<#
.SYNOPSIS
  Archive files by extension while preserving directory structure.

.DESCRIPTION
  Recurses from -Root and archives only files matching -Extensions. Preserves
  relative paths. Supports excludes, timestamped output names, and ZIP/RAR/7z.
  Supports wildcard patterns in extensions, including double extensions (e.g., 
  .vcxproj.filters). Hidden files/folders are excluded by default unless 
  -IncludeHidden is specified.

.PARAMETER Root
  The root directory to scan. Can be relative (e.g., ..\..) or absolute.

.PARAMETER Dest
  Destination archive path, including filename (e.g., .\output.zip).
  Relative paths are resolved to absolute paths before archiving.

.PARAMETER Extensions
  One or more file extensions to include (e.g., ".c",".h",".cpp",".hpp").
  Case-insensitive; with or without leading dots. Supports wildcards (* and ?).
  Handles double extensions: ".vcxproj*" matches .vcxproj, .vcxproj.filters, .vcxproj.user
  Examples: ".h*" matches .h, .hpp, .hxx; ".c??" matches .cpp, .cxx
  (Use -IncludeNoExtension for files with no extension.)

.PARAMETER ExcludeDirs
  One or more directory names (relative to -Root) to exclude (e.g., ".git","build").
  Defaults to common build/junk folders. Directories that don't exist are ignored.

.PARAMETER Format
  Archive format to create: "zip", "rar", "7z", or "auto".
  When "auto", the format is inferred from the -Dest extension.

.PARAMETER Force
  Overwrite the destination archive if it already exists.

.PARAMETER TimestampPrefixFormat
  If provided, prefixes the output filename with a timestamp generated by
  (Get-Date).ToString(<format>). Example: "[yyyy.MM.dd HH.mm.ss]".
  Illegal filename characters are replaced for Windows compatibility.

.PARAMETER IncludeNoExtension
  Include files that have no extension at all (i.e., filename has no dot suffix).

.PARAMETER IncludeHidden
  Include hidden files and folders in the archive. By default, hidden items are excluded.

.PARAMETER IncludeRootFolder
  Keep the top-level root folder name inside the archive. By default, only the
  contents are archived. With this switch, the root folder itself is included.

.INPUTS
  None. All input is via parameters.

.OUTPUTS
  System.String (console message on completion). Creates the archive on disk.

.EXAMPLE
  # Basic: zip all .c and .h from current dir (excludes hidden files by default)
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\output.zip" -Extensions ".c",".h"
  
.EXAMPLE
  # Include hidden files and folders
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\output.zip" -Extensions ".c",".h" -IncludeHidden
  
.EXAMPLE
  # Use wildcards: match all .h* files (.h, .hpp, .hxx, etc.)
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\headers.zip" -Extensions ".h*"
  
.EXAMPLE
  # Multiple wildcard patterns
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\source.zip" -Extensions ".c*",".h*"
  
.EXAMPLE
  # Match double extensions: .vcxproj, .vcxproj.filters, .vcxproj.user
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\project.zip" -Extensions ".vcxproj*",".sln"
  
.EXAMPLE
  # Match .cpp, .cxx with single wildcard pattern
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\cpp.zip" -Extensions ".c??"
  
.EXAMPLE
  # Choose *.RAR (requires WinRAR), custom excludes
  .\Backup-MatchingFiles.ps1 -Root "C:\proj" -Dest "C:\proj\out\code.rar" -Extensions ".c",".h" -Format rar -ExcludeDirs ".git","build","out","third_party"
  
.EXAMPLE
  # Use *.7z (requires 7-Zip)
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\src.7z" -Extensions "c","h","cpp","hpp" -Format 7z
  
.EXAMPLE
  # *.zip with no excludes and overwrite if exists
  .\Backup-MatchingFiles.ps1 -Root "." -Dest ".\src.zip" -Extensions ".c",".h" -ExcludeDirs @() -Force
  
.EXAMPLE
  # Include the root folder itself in the archive structure
  .\Backup-MatchingFiles.ps1 -Root "C:\myproject" -Dest ".\backup.zip" -Extensions ".cs",".csproj" -IncludeRootFolder
  
.EXAMPLE
  # Include files with no extension, add timestamp prefix
  .\Backup-MatchingFiles.ps1 `
    -Root ..\.. `
    -Dest .\output.zip `
    -Extensions ".c",".h",".cpp",".hpp" `
    -IncludeNoExtension `
    -TimestampPrefixFormat "[yyyy.MM.dd HH.mm.ss]"

.NOTES
  Created: 2025.10.01
  Updated: 2025.10.14 - Added wildcard support (including double extensions) and optional hidden file support
  File:    $PSCommandPath
#>
[CmdletBinding()]
param
(
  # Directory to scan for files
  [Parameter(Mandatory=$true)]
  [string]$Root,

  # Output archive file path
  [Parameter(Mandatory=$true)]
  [string]$Dest,

  # Accept with or without leading dots: ".c","h" both OK
  # Supports wildcards: ".h*", ".c??", etc.
  [Parameter(Mandatory=$true)]
  [string[]]$Extensions,

  # Relative to $Root; default common build/junk dirs
  [string[]]$ExcludeDirs = @(".git","build","bin","obj",".vs",".idea","node_modules","dist","out"),

  # zip | rar | 7z | auto
  [ValidateSet("zip","rar","7z","auto")]
  [string]$Format = "zip",

  # If provided, prefix the output filename with a formatted timestamp (e.g. "[yyyy.MM.dd HH.mm.ss]")
  [string]$TimestampPrefixFormat,

  # Keep the top-level root folder name inside the archive?
  [switch]$IncludeRootFolder,

  # Overwrite destination if it already exists?
  [switch]$Force,

  # Include files that have no extension at all?
  [switch]$IncludeNoExtension,

  # Include hidden files and folders?
  [switch]$IncludeHidden
)

function Normalize-Ext
{
  param([string]$e)

  if ([string]::IsNullOrWhiteSpace($e))
  {
    # explicit "" = "no extension"
    # only used if IncludeNoExtension is set.
    return ""
  }

  if ($e.StartsWith("."))
  {
    return $e.ToLowerInvariant()
  }
  else
  {
    return ".$($e.ToLowerInvariant())"
  }
}

function New-ZipFromList
{
  <#
  .SYNOPSIS
    Creates a ZIP archive from a list of files, with preserved directory 
	structure.
  
  .DESCRIPTION
    Creates a new ZIP archive containing the specified files. Files are added 
	with their relative paths preserved, maintaining the original directory
	structure.
    Uses .NET's System.IO.Compression with optimal compression.
  
  .PARAMETER DestinationZip
    Full path where the ZIP archive will be created. The parent directory will be
    created if it doesn't exist.
  
  .PARAMETER BaseDir
    Base directory from which relative paths are resolved. All files to be archived
    must be located under this directory.
  
  .PARAMETER RelativePaths
    Array of file paths relative to BaseDir to include in the archive. Each path
    will be preserved in the archive structure (e.g., "src\file.c" becomes "src/file.c").
  
  .OUTPUTS
    None. Creates a ZIP file at the specified destination path.
  
  .EXAMPLE
    New-ZipFromList -DestinationZip "C:\output.zip" -BaseDir "C:\project" -RelativePaths @("src\main.c", "include\header.h")
    Creates output.zip containing src/main.c and include/header.h
  #>
  param
  (
    [Parameter(Mandatory=$true)][string]  $DestinationZip, # output ZIP file path
    [Parameter(Mandatory=$true)][string]  $BaseDir,        # base directory for relative paths
    [Parameter(Mandatory=$true)][string[]]$RelativePaths   # files to archive (relative to BaseDir)
  )

  # load the .NET assemblies necessary for ZIP file manipulation
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  Add-Type -AssemblyName System.IO.Compression

  # verify that the destination folder exists
  $destParent = Split-Path -Parent $DestinationZip
  if (-not [string]::IsNullOrWhiteSpace($destParent) -and 
     (-not (Test-Path -LiteralPath $destParent))) 
  {
    New-Item -ItemType Directory -Force -Path $destParent | Out-Null
  }

  # create archive, and then add entries with the relative names 
  # (preserves tree)
  $zip = [System.IO.Compression.ZipFile]::Open($DestinationZip, [System.IO.Compression.ZipArchiveMode]::Create)
  try 
  {
	# add each file to the archive with its relative path preserved
	foreach ($rel in $RelativePaths) 
	{
	  # construct full source path
	  $src = Join-Path $BaseDir $rel
	  
	  # skip if file no longer exists (edge case: deleted between enumeration and archiving)
	  if (-not (Test-Path -LiteralPath $src))
	  {
		continue 
	  }
	  
	  # convert backslashes to forward slashes (ZIP standard uses '/')
	  $entryName = $rel -replace '\\','/'
	  
	  # add file to archive with optimal compression
	  [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
		$zip, 
		$src, 
		$entryName, 
		[System.IO.Compression.CompressionLevel]::Optimal
	  ) | Out-Null
	}
  }
  finally 
  {
    # verify that ZIP file handle is properly closed even if an error occurs
	$zip.Dispose()
  }
}

function Add-TimestampPrefixToDest
{
  <#
  .SYNOPSIS
    Adds a timestamp prefix to a file path.
  
  .DESCRIPTION
    Prefixes the filename portion of a path with a formatted timestamp. The timestamp
    format is specified using standard .NET DateTime format strings. Invalid filename
    characters in the timestamp are replaced with hyphens for Windows compatibility.
  
  .PARAMETER DestPath
    The original file path to modify. Can be relative or absolute.
  
  .PARAMETER Format
    A .NET DateTime format string (e.g., "yyyy.MM.dd HH.mm.ss"). If empty or whitespace,
    the original path is returned unchanged. Common format specifiers:
    - yyyy: 4-digit year
    - MM:   2-digit month
    - dd:   2-digit day
    - HH:   2-digit hour (24-hour)
    - mm:   2-digit minute
    - ss:   2-digit second
  
  .OUTPUTS
    System.String. Returns the path with the timestamp prefix added to the filename,
    or the original path if no format was provided.
  
  .EXAMPLE
    Add-TimestampPrefixToDest -DestPath "C:\backup\data.zip" -Format "yyyy.MM.dd"
    Returns: "C:\backup\2025.10.01 data.zip"
  
  .EXAMPLE
    Add-TimestampPrefixToDest -DestPath ".\output.zip" -Format "[yyyy.MM.dd HH.mm.ss]"
    Returns: ".\[2025.10.01 15.30.45] output.zip"
  #>
  param
  (
    [string]$DestPath,
    [string]$Format
  )

	# return unchanged if no format string provided
	if ([string]::IsNullOrWhiteSpace($Format))
	{
	  return $DestPath
	}

	# generate timestamp string from format
	$stamp = (Get-Date).ToString($Format)

	# sanitize for Windows filename: replace invalid characters with hyphens
	$invalid = [IO.Path]::GetInvalidFileNameChars()

	foreach ($ch in $invalid)
	{ 
	  $stamp = $stamp -replace [regex]::Escape($ch), "-" 
	}

	# remove leading/trailing whitespace from sanitized timestamp
	$stamp = $stamp.Trim()

	# split path into directory and filename components
	$dir  = Split-Path -Parent $DestPath
	$leaf = Split-Path -Leaf   $DestPath

	# prefix filename with timestamp (or keep original if stamp is empty after sanitization)
	$newLeaf = if ($stamp) 
	{ 
	  "$stamp $leaf"
	}
	else
	{
	  $leaf 
	}

	# return just the filename if there's no directory component
	if ([string]::IsNullOrWhiteSpace($dir))
	{
	  return $newLeaf
	}

	# rejoin directory and timestamped filename
	return (Join-Path $dir $newLeaf)
}

try
{
  # resolve absolute paths
  $rootFull = Resolve-Path -LiteralPath $Root | Select-Object -ExpandProperty Path

  # determine the archive format from `-Format` or `Dest` extension (when `auto`)
  if ($Format -eq "auto")
  {
    switch (([IO.Path]::GetExtension($Dest)).ToLowerInvariant())
    {
      ".zip" 
      { 
        $Format = "zip" 
      }
      ".rar" 
      { 
        $Format = "rar" 
      }
      ".7z"  
      { 
        $Format = "7z"  
      }
      default 
      {
        throw "Could not infer format from '$Dest'. Use -Format zip|rar|7z." 
      }
    }
  }

  # normalize extensions set
  $exts = $Extensions | ForEach-Object { Normalize-Ext $_ } | Select-Object -Unique

  # build excluded directory prefixes (absolute, with trailing separator)
  $excludeFullPrefixes = @()
  foreach ($d in $ExcludeDirs)
  {
	# skip empty or whitespace-only directory names
	if ([string]::IsNullOrWhiteSpace($d))
	{ 
	  continue 
	}

	$full = Join-Path $rootFull $d

	# skip directories that don't exist on disk
	if (-not (Test-Path -LiteralPath $full))
	{
	  continue
	}

	# verify that the path has a trailing separator for prefix matching
	if (-not $full.EndsWith([IO.Path]::DirectorySeparatorChar)) 
	{
	  $full = $full + [IO.Path]::DirectorySeparatorChar
	}

	$excludeFullPrefixes += $full.ToLowerInvariant()
  }

  # decide where relative paths should be based from
  $rootName  = Split-Path -Leaf $rootFull
  $stageBase = if ($IncludeRootFolder)
  { 
    Split-Path -Parent $rootFull
  } 
  else
  {
    $rootFull
  }
  
  # resolve `$Dest` to absolute path before changing directory
  $Dest = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Dest)
  
  Push-Location $stageBase
  try
  {
    # enumerate from the actual root on disk
    # -Force includes hidden files and folders (when -IncludeHidden is specified)
    if ($IncludeHidden)
    {
      $all = Get-ChildItem -LiteralPath $rootFull -Recurse -File -Force
    }
    else
    {
      $all = Get-ChildItem -LiteralPath $rootFull -Recurse -File
    }

    $files = foreach ($f in $all)
    {
      # exclude folders by absolute prefix
      $full  = $f.FullName
      $lower = $full.ToLowerInvariant()
      $skip  = $false
      
	  foreach ($prefix in $excludeFullPrefixes) 
      {
        if ($lower.StartsWith($prefix))
        { 
          $skip = $true
          break 
        }
      }
	  
      if ($skip)
      {
        continue
      }

      # extension match with wildcard support using -like operator
      # supports double extensions (e.g., .vcxproj.filters)
      $fileName = $f.Name.ToLowerInvariant()
      $hasListedExt = $false
      
      # extract all possible extension suffixes from the filename
      # for "project.vcxproj.filters" this gives: ".filters", ".vcxproj.filters"
      $possibleExts = @()
      $dotIndex = $fileName.IndexOf('.')
      while ($dotIndex -ge 0)
      {
        $possibleExts += $fileName.Substring($dotIndex)
        $dotIndex = $fileName.IndexOf('.', $dotIndex + 1)
      }
      
      # check if any suffix matches any pattern
      foreach ($pattern in $exts)
      {
        foreach ($ext in $possibleExts)
        {
          if ($ext -like $pattern)
          {
            $hasListedExt = $true
            break
          }
        }
        
        if ($hasListedExt)
        {
          break
        }
      }
      
      $hasNoExt = ($IncludeNoExtension -and $f.Extension -eq "")
      
      if (-not ($hasListedExt -or $hasNoExt)) 
      { 
        continue 
      }

      # relative path from rootFull
      $rel = $full.Substring($rootFull.Length).TrimStart('\','/')
      if ($IncludeRootFolder) 
      {
        Join-Path $rootName $rel
      } 
      else 
      {
        $rel
      }
    }

    # exit early if no matching files were found after filtering by extension 
	# and exclusions
    if (-not $files -or $files.Count -eq 0)
    {
      Write-Warning "No files found under '$Root' matching extensions: $($exts -join ', ')"
      return
    }

    # apply timestamp prefix (if any) before we create/check the destination
    $Dest = Add-TimestampPrefixToDest -DestPath $Dest -Format $TimestampPrefixFormat

    # ensure destination folder exists (only if parent is non-empty)
    $destParent = (Split-Path -Parent $Dest)
    if (-not [string]::IsNullOrWhiteSpace($destParent)) 
    {
      if (-not (Test-Path -LiteralPath $destParent)) 
      {
        New-Item -ItemType Directory -Force -Path $destParent | Out-Null
      }
    }

    # remove existing destination if -Force
    if (Test-Path -LiteralPath $Dest)
    {
      if ($Force) 
      {
        Remove-Item -LiteralPath $Dest -Force
      } 
      else 
      {
        throw "Destination '$Dest' already exists. Use -Force to overwrite."
      }
    }

    switch ($Format)
    {
      "zip"
      {
        # base directory must match the relative names we pass in $files
        $baseDir = if ($IncludeRootFolder) 
        { 
          Split-Path -Parent $rootFull 
        } 
        else 
        { 
          $rootFull 
        }
        New-ZipFromList -DestinationZip $Dest -BaseDir $baseDir -RelativePaths $files
      }
      "rar"
      {
        $rar = Get-Command rar -ErrorAction SilentlyContinue
        if (-not $rar) 
        { 
          throw "WinRAR 'rar.exe' not found in PATH. Install WinRAR or use -Format zip/7z." 
        }

        $listFile = [IO.Path]::GetTempFileName()
        try
        {
          # ASCII is fine for typical names; switch to UTF-8 if you expect non-ASCII and your rar.exe supports it
          Set-Content -LiteralPath $listFile -Value ($files -join [Environment]::NewLine) -Encoding ASCII

          # no -ep/-ep1 so RAR keeps the folder parts that were passed
          & $rar.Source -idq a -- "$Dest" "@$listFile"
          if ($LASTEXITCODE -ne 0) 
          { 
            throw "rar.exe failed with exit code $LASTEXITCODE." 
          }
        }
        finally
        {
          Remove-Item -LiteralPath $listFile -ErrorAction SilentlyContinue
        }
      }
      "7z"
      {
        $seven = Get-Command 7z -ErrorAction SilentlyContinue
        if (-not $seven) 
        { 
          throw "7-Zip '7z.exe' not found in PATH. Install 7-Zip or use -Format zip/rar." 
        }

        $listFile = [IO.Path]::GetTempFileName()
        try
        {
          # use UTF-8 (no BOM) and tell 7z to read UTF-8 list files
          $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
          [System.IO.File]::WriteAllLines($listFile, $files, $utf8NoBom)

          $ext = ([IO.Path]::GetExtension($Dest)).ToLowerInvariant()
          $t = switch ($ext) 
          { 
            ".7z" 
            { 
              "7z" 
            } 
            ".zip" 
            { 
              "zip" 
            } 
            default 
            { 
              "7z" 
            } 
          }

          & $seven.Source a "-t$t" "-scsUTF-8" "--" "$Dest" "@$listFile"
		  
          if ($LASTEXITCODE -ne 0) 
          { 
            throw "7z.exe failed with exit code $LASTEXITCODE." 
          }
        }
        finally
        {
          Remove-Item -LiteralPath $listFile -ErrorAction SilentlyContinue
        }
      }
    }

    Write-Host "Created archive: $Dest"
  }
  finally
  {
    Pop-Location
  }
}
catch
{
  Write-Error $_.Exception.Message
  
  exit 1
}