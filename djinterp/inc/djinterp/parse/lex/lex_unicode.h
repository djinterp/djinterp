/*******************************************************************************
* djinterp [parse]                                                 lex_unicode.h
*
* UTF-8 decoding and the identifier character classes of C and C++.
*   Which code points may appear in an identifier is a fact about the
* standard, and the standards disagree: C99 and C11 each published a closed
* table in an annex, and C23 and C++ replaced both with UAX #31's XID_Start
* and XID_Continue, which move with every Unicode release.  The set a dialect
* uses is one of the D_LEX_IDSET_* constants below, and every test here takes
* it, so the scanner asks one question whatever the language.
*   C++ uses UAX #31 at every level.  P1949 was adopted for C++23 as a defect
* report against the earlier standards, and both major compilers apply it
* retroactively; C, which made no such change, keeps its annexes until C23.
*   The tables are generated by tools/gen_unicode.py from the Unicode
* Character Database and are never edited by hand; d_lex_unicode_version
* names the release they came from.
*
*
* path:      /inc/djinterp/parse/lex/lex_unicode.h
* link(s):   TBA
* author(s): Samuel 'teer' Neal-Blim                         created: 2026.09.22
*                                                            revised: 2026.10.02
*******************************************************************************/

